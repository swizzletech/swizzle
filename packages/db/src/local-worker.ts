import { eq } from "drizzle-orm";
import { FULL_SCOPE } from "./access.js";
import { createPostgresApiTokenStore, hashApiToken } from "./api-tokens.js";
import { recordAuditChange } from "./audit-tables.js";
import { createDatabaseClient } from "./client.js";
import { workers } from "./schema.js";

/**
 * The packaged instance explicitly provisions its own machine, which serves every project and
 * environment of the instance. Remote enrollment stays owner-only and grant-scoped.
 */
export async function provisionLocalWorker(input: {
  readonly token: string;
  readonly capacity: number;
}): Promise<string> {
  if (!/^swz_[A-Za-z0-9_-]{43}$/.test(input.token))
    throw new Error(
      "SWIZZLE_LOCAL_WORKER_TOKEN must be an opaque worker token generated by just init-env.",
    );
  if (!Number.isInteger(input.capacity) || input.capacity < 1 || input.capacity > 256)
    throw new Error("Local worker capacity must be between 1 and 256.");
  const hash = hashApiToken(input.token);
  // The stable identity prevents a restart from recreating a worker the owner revoked.
  const id = `${hash.slice(0, 8)}-${hash.slice(8, 12)}-4${hash.slice(13, 16)}-a${hash.slice(17, 20)}-${hash.slice(20, 32)}`;
  const client = createDatabaseClient();
  try {
    await client.db.transaction(async (tx) => {
      const inserted = await tx
        .insert(workers)
        .values({
          id,
          name: "Local worker",
          local: true,
          profiles: ["host-default"],
          services: [],
          capacity: input.capacity,
          credentialGeneration: 1,
          enrollmentExpiresAt: new Date(),
        })
        .onConflictDoNothing({ target: workers.id })
        .returning({ id: workers.id });
      if (inserted.length === 0) {
        // Operator sizing never revives a revoked identity.
        await tx.update(workers).set({ capacity: input.capacity }).where(eq(workers.id, id));
        return;
      }
      await createPostgresApiTokenStore({ client: { ...client, db: tx } }).createToken({
        holder: { kind: "worker", workerId: id },
        name: "worker",
        scope: FULL_SCOPE,
        issuedBy: null,
        plaintext: input.token,
        expiresAt: "9999-12-31T00:00:00Z",
      });
      for (const action of ["created", "enrolled"] as const) {
        await recordAuditChange(tx, {
          change: { kind: "worker", workerId: id, action, issuedBy: null },
          actor: { kind: "system" },
          occurredAt: new Date().toISOString(),
        });
      }
    });
    return id;
  } finally {
    await client.close();
  }
}
